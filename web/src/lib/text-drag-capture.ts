import type { PointerEvent as ReactPointerEvent } from "react";

// ★★M31-02: popover の中に置いた検索欄で始めたドラッグの文字選択が、
//   ポインタが枠の外へ出ると消える件の回避。
//
//   開発者の逐語(2026-09-08)＝「テキストボックス上にマウスを合わせて左クリックする。
//   そのままドラッグしてポインタがテキストボックスの外に出ると、文字選択(青色になる)が消える」。
//
// ★実測(Playwright / Chromium。web/e2e/m31-02-*-drag.spec.ts が 2 部品とも固定する):
//   - **popover の枠外へ出ると**選択が anchor へ collapse する。
//     ★4 方向で測ると、修正前に赤になるのは **左と上の 2 件**である
//       (キャラ選択 = `[0, 4] → [4, 4]` ／ タグ欄 = `[0, 9] → [9, 9]`。同じ形)。
//   - 壊れる境界は popover の左端のちょうど 1px 外側(実測 x=93 の popover に対し x=92)。
//   - **同じ矩形へ重ねた素の <input> では起きない**。⇒ popover 側の条件が効いている。
// ★★出口の x をどこに置くかで、縦方向は再現したりしなかったりする
//   (脱出点を横中央に置いた調査では上も維持された。左端へ寄せると上も消える)。
//   ⇒ 「左だけ」と要約しないこと。**再現条件は方向ではなく枠外へ出ることである。**
// ★★「なぜ左と上でだけ再現するのか」は特定できていない。⇒ 原因ではなく回避を入れてある。
//   ポインタキャプチャを張ると、以後のポインタイベントが検索欄へ届き続け、
//   4 方向すべてで選択が維持される(実測。コンボ一覧・エディタの 2 画面で同型)。
//
// ★★実体を 1 本にしてある理由 —— **2 部品が同じ欠陥を持っていた**。
//   `SearchableSelect`(キャラ選択ほか 17 コントロール)と `TagSelector`(コンボ登録・編集の
//   タグ欄 1 面)は別実装だが、`Popover` + `Input` + `ul[role=listbox]` の構造が 1:1 である。
//   ★部品そのものは統合しない —— `M27-02a` の開発者裁定であり、波及の数が違う
//     (17 コントロール 対 1 面。片方の都合を他方へ持ち込まない)。
//   ⇒ `useListboxKeyNav` と同じ形で、**操作の実体だけを共有する**。
//   ★フックにしていないのは、state も ref も持たないためである。
//     `useListboxKeyNav` がフックなのは `listRef` を持つからであり、形を揃える理由は無い。
//
// ★マウスの主ボタンだけに限る。⇒ タッチ・ペンの挙動は 1 バイトも変えない。
//   根拠は「スマホ専用画面が在ること」ではなく、**これらの欄を持つ画面がいずれも
//   レスポンシブであり、タッチ環境でも使われること**である
//   (DES-005 §4.4 レスポンシブブレークポイント / §7 スマホUIの設計メモ)。右クリックも対象外。
// ★解放は pointerup / pointercancel で暗黙に起きるため、明示的な release は要らない。
export function handleTextDragPointerDown(
  e: ReactPointerEvent<HTMLInputElement>,
): void {
  if (e.pointerType !== "mouse" || e.button !== 0) return;
  try {
    e.currentTarget.setPointerCapture(e.pointerId);
  } catch {
    // ポインタが既に離れている等でキャプチャできない場合は、従来どおりの挙動へ落ちる。
    // jsdom には実体が無いため、単体テストはこの経路を通る。
  }
}
