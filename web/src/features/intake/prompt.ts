   【行単位に戻した例（取り込みやすい）】
   - 中足ラッシュ > 強P > 強波掌撃 > 中竜巻
   - 中足ラッシュ > 強P > 引き強P > 強昇竜
   - 中足ラッシュ > 強P > 引き強P > 強K > 強P > 強昇竜 > SA3
