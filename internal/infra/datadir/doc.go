// Package datadir は、正式名リネーム(M28-01)にともなう既定データディレクトリの
// 一度きりの移行を提供する。
//
// ★★本パッケージの不変条件は 1 つである ————————————————————————————————
//
//	検証が通るまで、旧ディレクトリの中身は失われない。
//
// ★★「1 バイトも書かない」ではない。移行のために 2 つの書き込みが検証より前に起きる。
//
//  1. acquireLock が旧ディレクトリ直下へ .migrating.lock を作る(二重起動を塞ぐため)。
//     ⇒ 移行が終われば消える。旧 DB には触らない。
//  2. checkpointWAL の PRAGMA wal_checkpoint(TRUNCATE) は WAL の内容を
//     **移行元 DB 本体へ書き戻す**。⇒ ファイルのバイト列は変わる。
//     ★破壊ではない——SQLite にとって等価な状態への畳み込みであり、やらなければ
//     WAL にしか無いコミットが移行先に載らない(copy.go checkpointWAL の注記)。
//
// ⇒ 保証しているのは「旧ディレクトリを開けば移行前と同じデータが読める」ことであって、
// バイト列の同一性ではない。テストもそう書き分けてある
// (WAL が無い経路は sha256 で、WAL が残っている経路は行数で見る＝(d3))。
//
// 手順は「コピー → 検証 → 新の確定 → (呼出側が config を書き換え) → 旧の退避」であり、
// この順序は入れ替えてはならない。理由は各関数の注記に書いてある。
//
// ★旧ディレクトリを削除しない。退避(リネーム)までが本パッケージの責務であり、
// 消すのは開発者の手番である(M28-01 指示書 §4-5)。
//
// ★本パッケージはログを出さない。移行は applog.Init より前に走らざるを得ない
// (ログ出力先が旧ディレクトリ配下の絶対パスでありうるため)ので、
// 結果を Result として返し、呼出側がロガー初期化後に 1 度だけ出す。
