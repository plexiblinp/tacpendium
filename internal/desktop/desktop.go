// ErrUnsupported is returned by RunTray on platforms without an implementation.
// Callers must treat it as "keep running without a tray icon", never as fatal —
// the browser UI still has a stop button.
var ErrUnsupported = errors.New("この OS では常駐アイコンに対応していません")

// TrayMenu describes the notification-area icon and its right-click menu.
// Every callback runs on the tray's own thread; keep them short and hand real
// work to another goroutine.
type TrayMenu struct {
	Title   string // menu header / dialog caption
	Tooltip string // hover text — this is the "is it running?" indicator
	Items   []TrayItem
}

// TrayItem is one right-click menu entry. Default marks the entry that also
// runs on a left double-click of the icon.
type TrayItem struct {
	Label   string
	OnClick func()
	Default bool
}

// ValidateURL rejects anything that is not a plain http/https URL, so a URL
// built from config (host / port) can never turn into an arbitrary
// shell/protocol invocation.
func ValidateURL(raw string) error {
	u, err := url.Parse(raw)
	if err != nil {
		return fmt.Errorf("URL を解釈できません: %w", err)
	}
	if u.Scheme != "http" && u.Scheme != "https" {
		return fmt.Errorf("http/https 以外の URL は開きません: %q", raw)
	}
	if u.Host == "" {
		return fmt.Errorf("ホストの無い URL は開きません: %q", raw)
	}
	return nil
}

// launchCmd is a helper process to start, plus how to show it.
type launchCmd struct {
	Name string
	Args []string
	// HideWindow は「ヘルパ自身のウィンドウを隠すか」。
	//
	//	true  — 「対象を起動して即座に消えるだけ」のヘルパ。隠さないと一瞬ウィンドウが
	//	        出て、M34 で消したはずの黒窓が復活する。
	//	false — explorer のように「そのウィンドウこそが目的」のプロセス。
	//	        隠すとプロセスは起動するのに画面には何も出ず、Start() も成功するので
	//	        エラーにすらならない(2026-08-04 の実機検証で踏んだ不具合)。
	//
	// ★★現在 true を立てる呼び手は無い(M34-02 段 6 でブラウザ起動を pkg/browser へ
	// 委譲したため。それまでは rundll32 が true だった)。⇒ フィールドを残してあるのは、
	// 「explorer を隠してはならない」という上記の実機知見をこの false が型で保っている
	// からである(回帰テスト TestFolderCommandNeverHidesWindow が対応する)。
	HideWindow bool
}

// folderCommand builds the "reveal this directory" command for a GOOS.
func folderCommand(goos, dir string) (launchCmd, error) {
	if dir == "" {
		return launchCmd{}, errors.New("フォルダのパスが空です")
	}
	switch goos {
	case "windows":
		// explorer のウィンドウを見せるのが目的なので、絶対に隠さない。
		return launchCmd{"explorer.exe", []string{dir}, false}, nil
	case "darwin":
		return launchCmd{"open", []string{dir}, false}, nil
	default:
		return launchCmd{"xdg-open", []string{dir}, false}, nil
	}
}

// iconImage extracts the first image's raw bytes from an .ico file.
//
// CreateIconFromResourceEx wants the image payload (BITMAPINFOHEADER + pixels),
// not the ICONDIR/ICONDIRENTRY header that prefixes a file on disk — so the
// directory entry is parsed to find where the payload starts. Kept here rather
// than in the Windows file so it can be tested on any platform.
func iconImage(ico []byte) ([]byte, error) {
	const (
		dirSize   = 6  // ICONDIR: reserved(2) type(2) count(2)
		entrySize = 16 // ICONDIRENTRY
	)
	if len(ico) < dirSize+entrySize {
		return nil, errors.New("ico が短すぎます")
	}
	if binary.LittleEndian.Uint16(ico[0:2]) != 0 || binary.LittleEndian.Uint16(ico[2:4]) != 1 {
		return nil, errors.New("ico のヘッダが不正です")
	}
	if binary.LittleEndian.Uint16(ico[4:6]) == 0 {
		return nil, errors.New("ico に画像が入っていません")
	}
	size := binary.LittleEndian.Uint32(ico[dirSize+8 : dirSize+12])
	off := binary.LittleEndian.Uint32(ico[dirSize+12 : dirSize+16])
	end := uint64(off) + uint64(size)
	if size == 0 || end > uint64(len(ico)) {
		return nil, fmt.Errorf("ico の画像位置が不正です (offset=%d size=%d len=%d)", off, size, len(ico))
	}
	return ico[off:end], nil
}

// OpenURL launches the user's default browser.
//
// ★★いつ返るかは OS で違う。⇒ 「すぐ返る」を前提にしないこと ————————————
// 委譲前(自前の spawn = exec.Command(...).Start())は常にすぐ返っていたが、
// pkg/browser の実装は次のとおりである(実測 v0.0.0-20240102092130-5ac0b6a4141c)。
//
//	Windows      — windows.ShellExecute。子プロセスを spawn せず、すぐ返る。
//	Linux/macOS  — xdg-open / open を exec.Command(...).Run() で起動するため、
//	               そのヘルパが終わるまで返らない。
//
// ⇒ 本体の呼び手 3 つのうち、トレイのメニュー(desktop.invoke が go で回す)と
// launchBrowser(自前の goroutine)は待たない形になっている。二重起動の判別
// (openExistingInstance)だけは同期で呼ぶ —— そのまま退くプロセスであり、
// 開けたかどうかを知る必要があるためである。
//
// ★★実際の起動は github.com/pkg/browser へ委譲する(M34-02 段 6 / followup
// `browser-launch-duplication`) ————————————————————————————————————————————
// 移植直後は rundll32 を自前で叩いていた。移植元のコメントは「cmd /c start だと黒窓が
// 一瞬出る」を理由に自前実装を選んでいたが、その理由は本体では成立しない ——
// pkg/browser の Windows 実装は ShellExecute であって黒窓を出さないし、同モジュールは
// 元から go.mod の direct 依存である(移植元は外部依存 0 本のリポジトリだった)。
// ⇒ 経路を 2 本持つと CLAUDE.md §6「重複機能ライブラリは導入しない」の趣旨から外れる。
//
// ★★ValidateURL は捨てない —— 設定由来の文字列が任意のプロトコル起動に化けるのを
// 防ぐ唯一の関門である。⇒ 委譲する前に必ず通す。
func OpenURL(raw string) error {
	if err := ValidateURL(raw); err != nil {
		return err
	}
	return browser.OpenURL(raw)
}

// OpenFolder shows dir in the platform file manager (tray menu convenience:
// that is where the log file and the DB land — M34-overview §5.1.6 の
// 「ログフォルダを開く」と「DB のフォルダを開く」がこれを使う).
//
// The directory is stat'd first: the file manager is started and never waited
// on, so a bad path would otherwise fail silently — "選んでも何も起きない" with
// nothing in the log to explain it.
func OpenFolder(dir string) error {
	c, err := folderCommand(runtime.GOOS, dir)
	if err != nil {
		return err
	}
	fi, err := os.Stat(dir)
	if err != nil {
		return fmt.Errorf("フォルダを確認できません(%s): %w", dir, err)
	}
	if !fi.IsDir() {
		return fmt.Errorf("フォルダではありません: %s", dir)
	}
	return spawn(c)
}
