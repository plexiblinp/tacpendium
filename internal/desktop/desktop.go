// Package desktop is the app's thin desktop-integration layer (M34):
// notification-area (tray) residency, native confirm/alert dialogs, and
// "open this in the user's browser / file manager".
//
// Why it exists: the app runs in a visible console window and is stopped by
// closing that window — which reads as "a developer thing" to a general user,
// and closing it by mistake kills the app. The Windows exe will therefore be
// built for the GUI subsystem (no console at all, M34-02) and this package
// provides what the console used to provide — a visible sign that the app is
// running, and a deliberate way to stop it.
//
// Design constraints (CLAUDE.md §6 = 依存ポリシー):
//   - go.mod に依存を足さない(ライセンス面の安全側)。Win32 は syscall.NewLazyDLL で
//     直接叩く。★M34-02 段 6 でブラウザ起動だけは既存の direct 依存
//     github.com/pkg/browser(BSD-2-Clause)へ委譲した ——
//     本体は元からそれを持っており、新規依存は 0 件のままである(go.mod / go.sum 無変更)。
//   - OS 依存は desktop_windows.go / desktop_other.go に閉じ込め、この
//     ファイルは純粋関数とプラットフォーム非依存の API だけを持つ(テスト可能)。
//   - 実装は Windows のみ。他 OS ではトレイは ErrUnsupported を返し、
//     アラートは stderr に落ちる(開発機が Linux/macOS でも動くように)。
//
// 移植元: 開発者本人の非公開リポジトリ autopilot-combomgr の
// projects/moves-input-tool/internal/desktop(M34-01 で移植)。第三者由来の断片は
// 無いことを実査済みで、出所と根拠は docs/progress/progress-log.md が正本。
// ライセンスは REUSE.toml の既定(層 A = AGPL-3.0-or-later)で解決される。
