// (M20-07)。
//
// ★本パッケージは照合専用である。表示経路から参照してはならない。
// 表示側へ掛けると `preset_aliases.alias_text` の見え方が変わり、D-307 が「採らない」と
// 決めたデータ書き換えと同じ結果になる(指示書 M20-07 §4.5-2)。正規化はデータを書き換えず、
// 照合のときだけ掛かる。
//
// ★入力側と辞書側の両方へ同じ関数を掛けること(§4.1-2)。片側だけに掛けると、掛けた側だけが
// 揃って一致しなくなる。この不変条件は internal/aliasindex が「投入時と照会時の両方で本
// パッケージを通す」形で構造的に守っている(internal/moveindex が トークン軸で採っている形と同じ)。
//
// # 採った範囲と、採らなかった範囲
//
// 範囲は実測で決めた(§4.1-1・§4.1-5＝同一視される組が 1 組でも生まれるなら採らない)。
// 実測は preset_aliases 全 4,184 行に対して行い、「同一キャラ内で、異なる move が同じ
// 正規化キーへ落ちる組」を数えた。
//
// 採った(いずれも同一視 0 組):
//   - NFKC        … 全角括弧 `（）`→`()` ・全角数字 `１`→`1` 等の幅の差を吸収する。
//     これが D-307 の本体である(NFKC 差分 38 行 / 全角括弧 35 行 / 半角と全角の混在 12 行)。
//   - 前後空白の除去
//   - 大文字小文字の畳み込み … `Back Microwalk` と書かれた英語表記を拾うため(§4.2)。
//
// 採らなかった(実測で同一視を生む。数値は同一キャラ内の衝突グループ数):
//   - 末尾注記の一律除去 … `(ラッシュ)` 272 組 / `(単発)` 24 組 / `(hold)` 23 組 /
//     `(ホールド)` 11 組 / `(2発止め)` 21 組。これらは技を区別している注記であり、
//     落とすと派生技が基底技へ吸収される。
//   - `(後)` の除去 … 19 組。しかもキャラ横断でしか見えない——`微歩き(後)`(micro_back)を
//     落とすと `微歩き`(micro_forward)と一致する。逆引きは全プリセット横断であるため
//     本番で成立する衝突であり、プリセット別の分析では見えない。
//   - 曖昧一致・編集距離 … DES-004 §5 冒頭注記が禁じている。決定論を壊す。
//
// SA / CA の注記だけは NormalizeRelaxed が落とすが、これは第 2 段専用である(下記)。
package aliasnorm

import (
	"regexp"
	"strings"

	"golang.org/x/text/unicode/norm"
)

// saCARelaxPattern は末尾の SA / CA 注記にだけ当たる(例 `236236p (sa1)` の ` (sa1)`)。
// Normalize が大文字小文字を畳んだ後の文字列に当てるため、パターン側も小文字で書く。
//
// ★落とす対象をこの 4 種へ意図的に絞ってある。`(ラッシュ)` のような「技を区別している注記」
// まで広げると別の技が同一視される(パッケージ docstring の実測値)。
//
// ★`sa[1-3]` と範囲を切ってあるのは、実データに存在するのが SA1 / SA2 / SA3 / CA の
// 4 種だけだからである(実測 132 行: SA1 38 / SA3 34 / CA 34 / SA2 26)。
// `sa[0-9]` と広く書くと、将来 `(SA4)` のような別の意味の注記が入ったときに
// 黙って落とし始める——落とす対象は「実在を確かめた分」に限る。
var saCARelaxPattern = regexp.MustCompile(`\s*\((sa[1-3]|ca)\)\s*$`)

// Normalize は逆引き照合の第 1 段で使う正規化キーを返す。
//
// NFKC → 前後空白の除去 → 大文字小文字の畳み込み、の順に掛ける。
// 実測で同一視される組は 0 であり(パッケージ docstring)、この段では「別の技が同じキーへ落ちる」
// ことが起きない。したがって第 1 段の結果が 1 件なら、それは決定論として確定してよい。
func Normalize(s string) string {
	return strings.ToLower(strings.TrimSpace(norm.NFKC.String(s)))
}

// NormalizeRelaxed は逆引き照合の第 2 段で使うキーを返す。Normalize に加えて、末尾の
// SA / CA 注記(`(SA1)` `(SA2)` `(SA3)` `(CA)`)を落とす。
//
// ★なぜ第 2 段が要るか——エイリアスは `236236P (SA1)` の形で入っているが、利用者はメモに
// `236236P` としか書かない(DES-004 §5.6 の 1 件目 / D-331 が M20-07 へ割り付けた)。
//
// ★★本関数のキーでは、別の技が同じキーへ落ちることが実際に起きる。実測で 17 組——
// 技データを持つ全 17 キャラで Critical Art と SA3 が同一コマンドであり、注記だけが
// 両者を区別している(例 guile `[4]646K (CA)` と `[4]646K (SA3)`)。
//
// ⇒ だから本関数の結果を「確定」に使ってはならない。呼び出し側は
//
//	(1) 第 1 段(Normalize)が 0 件のときにだけ第 2 段を引き、
//	(2) 第 2 段でも「1 件のときだけ確定」を崩さない
//
// という 2 条件を守ること。17 組は 2 件になるため未解決へ倒れ、候補として人へ提示される
// (開発者裁定 2026-08-14。指示書 §4.3-2 と同じ考え方＝どれが正しいかはメモの書き手しか知らない)。
func NormalizeRelaxed(s string) string {
	return saCARelaxPattern.ReplaceAllString(Normalize(s), "")
}
